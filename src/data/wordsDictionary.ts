export const getRandomPromptWord = (currentWord?: string): DailyPromptWord => {
  const available = currentWord
    ? PROMPT_WORDS.filter((w) => w.word.toLowerCase() !== currentWord.toLowerCase())
    : PROMPT_WORDS;
  return available[Math.floor(Math.random() * available.length)];
};

export const searchPromptWord = (query: string): DailyPromptWord => {
  const clean = query.trim().toLowerCase();
  const exact = PROMPT_WORDS.find((w) => w.word.toLowerCase() === clean);
  if (exact) return exact;

  const partial = PROMPT_WORDS.find(
    (w) =>
      w.word.toLowerCase().includes(clean) ||
      w.synonyms.some((s) => s.toLowerCase().includes(clean)) ||
      w.meaning.toLowerCase().includes(clean)
  );
  if (partial) return partial;

  // Fallback for custom user search: generate structured literary card
  const capitalized = clean.charAt(0).toUpperCase() + clean.slice(1);
  return {
    word: capitalized,
    category: 'Vocábulo Livre',
    meaning: `Expressão literária que carrega peso semântico e evoca imagens no imaginário do escritor.`,
    synonyms: [`Semelhante a ${capitalized}`, 'Analogia', 'Ressonância'],
    antonyms: ['Oposto conceitual', 'Contraponto'],
    poeticExample: `“A palavra ${capitalized} ecoava pelos corredores da narrativa como um presságio.”`,
    sparkIdea: `O que ${capitalized} significa para o destino do seu protagonista nesta cena?`,
  };
};
